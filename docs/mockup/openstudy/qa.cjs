function contrast(a,b){
  const luminance=hex=>{let value=hex.trim().replace('#','');if(value.length===3)value=value.split('').map(v=>v+v).join('');return [0,2,4].map(i=>parseInt(value.slice(i,i+2),16)/255).map(v=>v<=.04045?v/12.92:((v+.055)/1.055)**2.4).reduce((n,v,i)=>n+v*[.2126,.7152,.0722][i],0);};
  const x=luminance(a),y=luminance(b);return (Math.max(x,y)+.05)/(Math.min(x,y)+.05);
}
